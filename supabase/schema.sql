-- ── Berita ──────────────────────────────────────────────────────────────────
create table if not exists public.posts (
  id            bigint generated by default as identity primary key,
  slug          text        not null unique,
  title         text        not null,
  excerpt       text        not null default '',
  content       text[]      not null default '{}',
  cover_image   text        not null default '',
  category_slug text        not null references public.categories(slug) on update cascade,
  district_slug text,
  village_slug  text,
  author        text        not null default 'Redaksi Info Kelurahan',
  editor        text,
  source        text        not null default 'Info Kelurahan',
  source_url    text        not null default '',
  published_at  timestamptz not null default now(),
  views         integer     not null default 0 check (views >= 0),
  is_headline   boolean     not null default false,
  status        text        not null default 'published' check (status in ('published','draft')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists posts_published_idx on public.posts (status, published_at desc);
create index if not exists posts_category_idx  on public.posts (category_slug, published_at desc);
create index if not exists posts_district_idx  on public.posts (district_slug);
create index if not exists posts_village_idx   on public.posts (village_slug);
create index if not exists posts_views_idx     on public.posts (views desc);

-- Hanya satu headline aktif pada satu waktu
create unique index if not exists posts_single_headline_idx
  on public.posts ((true)) where is_headline = true;

-- ── Pengumuman ──────────────────────────────────────────────────────────────
create table if not exists public.announcements (
  id           bigint generated by default as identity primary key,
  title        text not null,
  body         text not null default '',
  level        text not null default 'info' check (level in ('info','penting','layanan')),
  published_at timestamptz not null default now(),
  expires_at   timestamptz,
  is_active    boolean not null default true
);

create index if not exists announcements_active_idx
  on public.announcements (is_active, published_at desc);

-- ── Agenda ──────────────────────────────────────────────────────────────────
create table if not exists public.agendas (
  id            bigint generated by default as identity primary key,
  title         text not null,
  description   text not null default '',
  location      text not null default '',
  starts_at     timestamptz not null default now(),
  ends_at       timestamptz,
  organizer     text not null default 'Pemerintah Kelurahan',
  district_slug text
);

create index if not exists agendas_start_idx on public.agendas (starts_at asc);

-- ── Trigger updated_at ──────────────────────────────────────────────────────
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists posts_touch_updated_at on public.posts;
create trigger posts_touch_updated_at
  before update on public.posts
  for each row execute function public.touch_updated_at();

-- ── Keamanan (RLS) ──────────────────────────────────────────────────────────
-- Aplikasi membaca & menulis melalui server Next.js memakai service role key.
-- RLS diaktifkan agar anon key tidak bisa menulis langsung dari peramban.
alter table public.posts         enable row level security;
alter table public.categories    enable row level security;
alter table public.announcements enable row level security;
alter table public.agendas       enable row level security;

-- Baca publik untuk konten terbit
drop policy if exists "posts_public_read" on public.posts;
create policy "posts_public_read" on public.posts
  for select using (status = 'published');

drop policy if exists "categories_public_read" on public.categories;
create policy "categories_public_read" on public.categories
  for select using (true);

drop policy if exists "announcements_public_read" on public.announcements;
create policy "announcements_public_read" on public.announcements
  for select using (is_active = true);

drop policy if exists "agendas_public_read" on public.agendas;
create policy "agendas_public_read" on public.agendas
  for select using (true);

-- Catatan: service role bypass RLS, sehingga dashboard admin tetap dapat
-- membuat, mengubah, dan menghapus berita.

-- ── Fungsi bantu statistik ──────────────────────────────────────────────────
create or replace function public.increment_post_views(post_id bigint)
returns void language sql security definer as $$
  update public.posts set views = views + 1 where id = post_id;
$$;
